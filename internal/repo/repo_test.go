func TestIsGeneratedByNameAndMarker(t *testing.T) {
	gen := []struct {
		path string
		head string
	}{
		{"api/service.pb.go", ""},
		{"store/query_gen.go", ""},
		{"web/app.min.js", ""},
		{"web/package-lock.json", ""},
		{"go.sum", ""},
		{"lib/model.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage lib\n"},
		{"lib/schema.ts", "/* @generated */\n"},
	}
	for _, c := range gen {
		if !IsGenerated(c.path, []byte(c.head)) {
			t.Errorf("IsGenerated(%q) = false, want true", c.path)
		}
	}
	for _, p := range []string{"internal/queue.go", "docs/generated-notes.md"} {
		if IsGenerated(p, []byte("package queue\n")) {
			t.Errorf("IsGenerated(%q) = true, want false", p)
		}
	}
}
